-- Migración aditiva: módulo de administración, aprobación de registros, visitas, emergencias y push.
-- En desarrollo (ddl-auto: update) Hibernate ya aplica estos cambios al arrancar.
-- En producción (ddl-auto: validate) ejecutar este script ANTES de desplegar la nueva versión.
-- No borra ni modifica datos existentes. Es idempotente (se puede ejecutar más de una vez).

BEGIN;

-- Usuarios: aprobación de autoregistros. Las cuentas existentes quedan aprobadas (DEFAULT true).
ALTER TABLE IF EXISTS app_users
    ADD COLUMN IF NOT EXISTS approved boolean DEFAULT true NOT NULL;

-- Visitas: motivo separado de las observaciones.
ALTER TABLE IF EXISTS visits
    ADD COLUMN IF NOT EXISTS reason varchar(200);

-- Emergencias: alerta general con registro de quién la activa y quién la resuelve.
CREATE TABLE IF NOT EXISTS emergencies (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone,
    message varchar(200),
    notified_count integer NOT NULL,
    resolution_notes varchar(300),
    resolved_at timestamp(6) with time zone,
    resolved_by_email varchar(160),
    status varchar(20) NOT NULL CHECK (status IN ('ACTIVE', 'RESOLVED')),
    triggered_by_email varchar(160) NOT NULL,
    triggered_by_name varchar(241) NOT NULL,
    triggered_from_apartment varchar(40),
    PRIMARY KEY (id)
);

-- Tokens push de dispositivos (Expo). Se usan solo si app.push.enabled=true.
CREATE TABLE IF NOT EXISTS push_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone,
    platform varchar(16),
    token varchar(200) NOT NULL,
    user_id bigint NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_push_tokens_token UNIQUE (token),
    CONSTRAINT fk_push_tokens_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

COMMIT;

-- Nota: la nueva audiencia de correo RESIDENTS_CONCIERGE cabe en mail_messages.audience (varchar(20)),
-- por lo que no requiere cambios de esquema.
